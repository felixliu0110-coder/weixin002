/* 服装四视图提示词：源自 .agnes/jimeng-2026-08-16-8289-通用服装四视图提示词模板.md
   结构：任务定义 → 四视图规格 → 参考图锚定 → 画面 → 禁止项 */
function buildGarmentViewsPrompt(garmentName, refCount) {
  const anchor = (refCount || 0) > 0
    ? `服装的版型、颜色、图案、面料质地以及纽扣、拉链等细节与参考图完全一致，不可自行更改款式。`
    : `服装的版型、颜色、面料细节真实自然。`;
  return `生成【${garmentName}】的服装四视图，四张视图以2x2均等排布在同一画布：
1. 左上角：服装正面平拍
2. 右上角：服装45度斜侧角度
3. 左下角：服装局部细节特写
4. 右下角：服装背面平拍
四个视角的服装为同一件，${anchor}
画面：纯白色背景，自然日常光线，服装平铺无遮挡，呈现自然真实的效果。
禁止：四个视角款式不一致，服装变形或串色，添加参考图中没有的配饰，人体模特，画面文字与水印。`;
}

module.exports = { buildGarmentViewsPrompt };
